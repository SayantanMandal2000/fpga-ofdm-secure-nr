#!/usr/bin/env python3
"""Generate rtl/sincos_lut.v : quarter-wave sin table, 1024-step phase, Q2.14."""
import math, sys
out = sys.argv[1] if len(sys.argv) > 1 else "rtl/sincos_lut.v"
L = []
L.append("// Auto-generated by scripts/gen_sincos_lut.py")
L.append("// sincos_lut : cos/sin of 2*pi*phase/1024, signed Q2.14 (16384 = 1.0).")
L.append("// Quarter-wave table S(i) = sin(2*pi*i/1024), i = 0..256, plus symmetry.")
L.append("`timescale 1ns / 1ps")
L.append("module sincos_lut (")
L.append("    input  wire [9:0]         phase,")
L.append("    output reg  signed [15:0] cos_o,")
L.append("    output reg  signed [15:0] sin_o")
L.append(");")
L.append("    function signed [15:0] qs;")
L.append("        input [8:0] i;")
L.append("        begin")
L.append("            case (i)")
for i in range(257):
    v = round(16384 * math.sin(2 * math.pi * i / 1024))
    L.append(f"                9'd{i:<3d}: qs = 16'sd{v};")
L.append("                default: qs = 16'sd16384;")
L.append("            endcase")
L.append("        end")
L.append("    endfunction")
L.append("")
L.append("    wire [7:0]         idx = phase[7:0];")
L.append("    wire signed [15:0] sa  = qs({1'b0, idx});          // S(idx)")
L.append("    wire signed [15:0] sb  = qs(9'd256 - {1'b0, idx}); // S(256-idx)")
L.append("")
L.append("    always @(*) begin")
L.append("        case (phase[9:8])")
L.append("            2'd0: begin cos_o =  sb; sin_o =  sa; end")
L.append("            2'd1: begin cos_o = -sa; sin_o =  sb; end")
L.append("            2'd2: begin cos_o = -sb; sin_o = -sa; end")
L.append("            default: begin cos_o = sa; sin_o = -sb; end")
L.append("        endcase")
L.append("    end")
L.append("endmodule")
open(out, "w").write("\n".join(L) + "\n")
# self-check of the symmetry mapping
S = [round(16384 * math.sin(2 * math.pi * i / 1024)) for i in range(257)]
worst = 0
for p in range(1024):
    q, i = p >> 8, p & 255
    a, b = S[i], S[256 - i]
    c, s = [(b, a), (-a, b), (-b, -a), (a, -b)][q]
    worst = max(worst, abs(c - 16384 * math.cos(2 * math.pi * p / 1024)), abs(s - 16384 * math.sin(2 * math.pi * p / 1024)))
print("max LUT error (LSB):", round(worst, 3))
